"""Generate include/game.h from game_fields*.tsv, slot_fields*.tsv, game_methods*.txt, game_prelude*.h.

Several lanes (workers) each own a `_<lane>` file of each kind; this tool merges them. Fields: offset<TAB>size<TAB>decl.
Identical duplicates are merged, conflicts print a WARNING (first file in sorted order wins). Every M_xxxxxxxx used in
src/*.cpp without an explicit declaration gets `void M_xxxxxxxx();`. Output is written atomically.
"""
import glob, os, re, sys, time
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.makedirs(os.path.join(D, "include"), exist_ok=True)


def files(pattern):
    return sorted(glob.glob(os.path.join(D, pattern)))


def read_fields(pattern):
    seen = {}
    for path in files(pattern):
        for line in open(path, encoding="utf-8"):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            off, size, decl = line.split("\t", 2)
            off, size = int(off, 0), int(size, 0)
            if off in seen:
                if seen[off] != (size, decl):
                    print("WARNING: field conflict at %#x: %r vs %r (%s)" % (off, seen[off][1], decl, os.path.basename(path)), file=sys.stderr)
                continue
            seen[off] = (size, decl)
    out, pos = [], 0
    for off in sorted(seen):
        size, decl = seen[off]
        if off < pos:
            print("WARNING: field at %#x overlaps previous field, skipped: %s" % (off, decl), file=sys.stderr)
            continue
        out.append((off, size, decl))
        pos = off + size
    return out


def emit_struct(name, total, fields, methods):
    lines = ["struct %s {" % name]
    pos = 0
    for off, size, decl in fields:
        if off > pos:
            lines.append("    char pad%x[%#x];" % (pos, off - pos))
        lines.append("    %s" % decl)
        pos = off + size
    if total is not None:
        if total < pos:
            sys.exit("%s: fields exceed total size" % name)
        if total > pos:
            lines.append("    char pad%x[%#x];" % (pos, total - pos))
    lines += ["    %s" % m for m in methods]
    lines.append("};")
    return "\n".join(lines)


def methods():
    explicit = {}
    free = []
    for path in files("config/game_methods*.txt"):
        for line in open(path, encoding="utf-8"):
            line = line.rstrip("\n")
            if not line.strip():
                continue
            m = re.search(r"\bM_([0-9a-f]{8})\b", line)
            if not m:
                free.append(line)
                continue
            if m.group(1) in explicit and explicit[m.group(1)] != line:
                print("WARNING: method M_%s declared twice: %r vs %r" % (m.group(1), explicit[m.group(1)], line), file=sys.stderr)
                continue
            explicit[m.group(1)] = line
    used = set()
    for f in files("src/*.cpp"):
        used |= set(re.findall(r"\bM_([0-9a-f]{8})\b", open(f, encoding="utf-8").read()))
    for a in sorted(used - set(explicit)):
        explicit[a] = "void M_%s();  /* stub */" % a
    return free + [explicit[k] for k in sorted(explicit)]


def main():
    prelude = "\n".join(open(p, encoding="utf-8").read() for p in files("config/game_prelude*.h"))
    out = ["/* GENERATED by tools/gen_game_h.py. Do not edit. */", "#ifndef TSH_GAME_H", "#define TSH_GAME_H", "", prelude, "",
           emit_struct("Slot", 0x50f4, read_fields("config/slot_fields*.tsv"), []), "",
           emit_struct("Game", 0x21efbf8, read_fields("config/game_fields*.tsv"), methods()), "", "#endif", ""]
    target = os.path.join(D, "include", "game.h")
    tmp = target + ".%d.tmp" % os.getpid()
    open(tmp, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    for attempt in range(20):
        try:
            os.replace(tmp, target)
            return
        except PermissionError:
            time.sleep(0.25)
    os.remove(tmp)


main()
